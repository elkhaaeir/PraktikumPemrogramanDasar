putaran = 5
distance = 14
pi = 3.14

cicumference = distance / (putaran * 2 * pi)

print("Diketahui :")
print(f"Pak Dengklek mengelilingi taman = {putaran} Putaran")
print(f"Jarak tempuh Pak Dengklek = {distance} Kilometer")
print("\n")
print("Jawaban :")
print(f"Jari-jari taman yang dikelilingi Pak Dengklek adalah {cicumference:.2f} Kilometer")